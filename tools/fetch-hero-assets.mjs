// Generator for the bundled hero constants + art used by the draft overlays. Run with
// `node tools/fetch-hero-assets.mjs "<path to the 'dota 2 beta' install>"`, then
// tools/generate-hero-posters.mjs. Hero ids and names come from OpenDota's public constants and the
// fearless icons from the Valve CDN; the draft pick-slot videos are the game's own animated hero
// portraits, copied from the local install. The output is committed: heroesData.ts,
// heroIcons/*.png and heroVideos/*.webm. A generated .ts module (not JSON) is emitted so it compiles
// cleanly under both the NodeNext and ES2022 tsconfigs.
import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dotaDir = process.argv[2];
if (dotaDir === undefined) {
  throw new Error('Pass the Dota 2 install folder, e.g. ".../steamapps/common/dota 2 beta".');
}

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEROES_TS = join(ROOT, 'src/shared/heroes/heroesData.ts');
const ICON_DIR = join(ROOT, 'src/overlay/elements/fearlessDraft/heroIcons');
const VIDEO_DIR = join(ROOT, 'src/overlay/elements/draftScreen/heroVideos');
const CDN_BASE = 'https://cdn.cloudflare.steamstatic.com';

const HERO_NAME_PREFIX = 'npc_dota_hero_';

async function main() {
  const response = await fetch('https://api.opendota.com/api/constants/heroes');
  if (!response.ok) {
    throw new Error(`OpenDota constants returned ${response.status}`);
  }

  const raw = Object.values(await response.json());
  const heroes = raw
    .map((hero) => ({
      id: hero.id,
      internalName: String(hero.name).replace(HERO_NAME_PREFIX, ''),
      localizedName: hero.localized_name,
      img: hero.img
    }))
    .sort((a, b) => a.id - b.id);

  await mkdir(dirname(HEROES_TS), { recursive: true });
  const rows = heroes
    .map(
      ({ id, internalName, localizedName }) =>
        `  { id: ${id}, internalName: ${JSON.stringify(internalName)}, localizedName: ${JSON.stringify(localizedName)} }`
    )
    .join(',\n');
  const module = `// Generated by tools/fetch-hero-assets.mjs from OpenDota constants — do not edit by hand.
// id matches both the GSI hero id and OpenDota hero_id.

export interface HeroConstant {
  readonly id: number;
  readonly internalName: string;
  readonly localizedName: string;
}

export const HEROES: readonly HeroConstant[] = [
${rows}
];
`;
  await writeFile(HEROES_TS, module);
  console.log(`Wrote ${heroes.length} heroes to heroesData.ts`);

  await mkdir(ICON_DIR, { recursive: true });
  let ok = 0;
  for (const hero of heroes) {
    // img looks like "/apps/dota2/images/dota_react/heroes/antimage.png?"; strip the trailing query.
    const path = String(hero.img).split('?')[0];
    const iconResponse = await fetch(`${CDN_BASE}${path}`);
    if (!iconResponse.ok) {
      console.warn(`  ! ${hero.internalName}: icon ${iconResponse.status}`);
      continue;
    }
    const buffer = Buffer.from(await iconResponse.arrayBuffer());
    await writeFile(join(ICON_DIR, `${hero.internalName}.png`), buffer);
    ok += 1;
  }
  console.log(`Downloaded ${ok}/${heroes.length} hero icons`);

  // The game's animated draft portraits, one per hero. The folder also holds persona variants and
  // portraits under old codenames (armadillo = Pangolier, sylph = Dark Willow), which GSI never names.
  await mkdir(VIDEO_DIR, { recursive: true });
  const portraitDir = join(dotaDir, 'game/dota/panorama/videos/heroes');
  let videosOk = 0;
  for (const hero of heroes) {
    try {
      await copyFile(
        join(portraitDir, `${HERO_NAME_PREFIX}${hero.internalName}.webm`),
        join(VIDEO_DIR, `${hero.internalName}.webm`)
      );
      videosOk += 1;
    } catch {
      console.warn(`  ! ${hero.internalName}: no portrait in the game files`);
    }
  }
  console.log(`Copied ${videosOk}/${heroes.length} hero portraits`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
